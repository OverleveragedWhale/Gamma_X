#!/usr/bin/env python3
"""Build the indicator and the strategy from pine/src/gx_killzones.pine.

    python pine/build.py

The strategy is the indicator plus orders at the marked points, so the two
cannot drift: the indicator's table is the conservative tally (a bar touching
stop and target is the stop), the Strategy Tester's fills follow TradingView's
broker emulator, which can differ on exactly those bars.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = (HERE / "src" / "gx_killzones.pine").read_text(encoding="utf-8")
COMMON = "overlay = true, max_lines_count = 500, max_labels_count = 500"
NOTE = "// GENERATED by pine/build.py from pine/src/gx_killzones.pine - edit the source.\n"

ind = SRC.replace("//@@HEADER", f'indicator("Gamma/X Killzone Sweeps", shorttitle = "GX KZ", {COMMON})')
for m in ("//@@BE", "//@@EXIT", "//@@ENTRY", "//@@FLAT"):
    ind = ind.replace(m, "// (strategy order point)")

strat = SRC.replace("//@@HEADER",
    f'strategy("Gamma/X Killzone Sweeps (strategy)", shorttitle = "GX KZ strat", {COMMON},\n'
    '         process_orders_on_close = true, default_qty_type = strategy.fixed, default_qty_value = 1,\n'
    '         commission_type = strategy.commission.cash_per_contract, commission_value = 0, slippage = 0)')
strat = strat.replace("                //@@BE",
    '                strategy.exit("GX x", "GX", stop = ePx, limit = tPx)')
strat = strat.replace("    //@@EXIT",
    '    strategy.close("GX", comment = exitHow)')
strat = strat.replace("        //@@ENTRY",
    '        strategy.entry("GX", sigDir > 0 ? strategy.long : strategy.short)\n'
    '        strategy.exit("GX x", "GX", stop = sPx, limit = tPx)')
strat = strat.replace("//@@FLAT",
    '// flat on the last bar before the killzone\'s flat time, at its close\n'
    'if strategy.position_size != 0 and dir != 0 and closeHm == tFlat\n'
    '    strategy.close("GX", comment = "time")')
assert "//@@" not in ind and "//@@" not in strat
(HERE / "gx_killzone_sweeps.pine").write_text(NOTE + ind, encoding="utf-8")
(HERE / "gx_killzone_sweeps_strategy.pine").write_text(NOTE + strat, encoding="utf-8")
print("built", HERE / "gx_killzone_sweeps.pine", HERE / "gx_killzone_sweeps_strategy.pine")
